  function quote(name) {
    const key = nameKey(name);
    if (key === 'coins') return { price: 1, source: 'Coins' };
    if (overrides.has(key)) return { price: overrides.get(key), source: 'Custom price' };
    const item = market.get(key);
    if (item) {
      const price = cache.prices[item.id] ?? item.price;
      if (validPrice(price) && price > 0) return { price, source: 'GE instant buy' };
    }
    if (shop.has(key)) return { price: shop.get(key), source: 'NPC shop' };
    if (taxidermy.has(key)) return { price: taxidermy.get(key), source: 'Taxidermist fee' };
    return { price: null, source: 'Unpriced' };
  }
  function set(name, price) {
    const key = nameKey(name);
    if (!key) throw new TypeError('Enter a material name.');
    if (price !== null && !validPrice(price)) throw new RangeError('Use a whole GP amount of zero or more.');
    if (key === 'coins' && price !== null && price !== 1) throw new RangeError('Coins are worth 1 GP each.');
    if (price === null) overrides.delete(key);
    else overrides.set(key, price);
    save(overridesKey, Object.fromEntries(overrides));
  }
